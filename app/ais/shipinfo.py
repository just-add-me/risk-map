def category(ship_type: Optional[int]) -> str:
    t = ship_type or 0
    if 70 <= t <= 79:
        return "cargo"
    if 80 <= t <= 89:
        return "tanker"
    if 60 <= t <= 69:
        return "passenger"
    if t in (36, 37):
        return "yacht"
    if t == 30:
        return "fishing"
    if 31 <= t <= 35 or 40 <= t <= 59:
        return "service"
    return "other"


def type_name(ship_type: Optional[int]) -> str:
    t = ship_type or 0
    if not t:
        return "Тип не передан"
    if t in _TYPE_NAMES:
        return _TYPE_NAMES[t]
    for lo, name in ((70, "Грузовое"), (80, "Танкер"), (60, "Пассажирское"), (40, "Скоростное"),
                     (20, "Экраноплан"), (90, "Прочее")):
        if lo <= t <= lo + 9:
            hz = _HAZARD.get(t - lo)
            return f"{name}, {hz}" if hz else name
    return f"Код типа {t}"


