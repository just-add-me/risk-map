def flag(mmsi: str) -> Optional[str]:
    """Флаг по MMSI. Только для судовых номеров (начинаются с 2–7)."""
    if len(mmsi) != 9 or not mmsi.isdigit() or mmsi[0] not in "234567":
        return None
    return MID.get(int(mmsi[:3]))


def dimensions(dim: Optional[dict]) -> tuple[Optional[float], Optional[float]]:
    """AIS передаёт расстояния от антенны до носа (A), кормы (B), левого (C) и правого (D) борта."""
    if not dim:
        return None, None
    a, b, c, d = (dim.get(k) or 0 for k in ("A", "B", "C", "D"))
    length = a + b if a + b > 0 and a < 511 and b < 511 else None
    beam = c + d if c + d > 0 and c < 63 and d < 63 else None
    return length, beam


def eta_text(eta: Optional[dict]) -> Optional[str]:
    """ETA из AIS: месяц, день, час, минута (UTC), без года. 0 = не задано."""
    if not eta or not eta.get("Month") or not eta.get("Day") or eta.get("Month") > 12 or eta.get("Day") > 31:
        return None
    hour, minute = eta.get("Hour", 24), eta.get("Minute", 60)
    t = f" {hour:02d}:{minute:02d} UTC" if hour < 24 and minute < 60 else ""
    return f"{eta['Day']:02d}.{eta['Month']:02d}{t}"
